#!/usr/bin/env python3
"""Turn the Grok images in art/raw/ into app assets.

  art/raw/<girl>_<emotion>.png  →  assets/girls/<girl>_<emotion>.jpg  (512×512, centre crop)
  art/raw/icon.png              →  assets/icon.png, assets/android-icon-foreground.png (1024×1024)
  art/raw/video/<girl>.mp4      →  assets/guard/<girl>.mp4  (480×480 silent loop for the screen-time overlay)

Writes src/data/art.ts with a require() for every portrait that exists, so the app shows real
art where it has it and falls back to the drawn faces elsewhere. Needs ffmpeg.
Run it again any time you add or replace images.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "art/raw"
OUT = ROOT / "assets/girls"
INDEX = ROOT / "src/data/art.ts"
VIDEO_INDEX = ROOT / "src/data/guard-videos.ts"
LINES = json.loads((ROOT / "src/data/lines.json").read_text())
EMOTIONS = ["love", "angry", "miss", "shy", "night", "call"]
CROP = "crop='min(iw,ih)':'min(iw,ih)'"


def ffmpeg(src: Path, dest: Path, size: int, extra: list[str]):
    dest.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-vf", f"{CROP},scale={size}:{size}:flags=lanczos",
         *extra, str(dest)],
        check=True,
    )


def corner_color(src: Path) -> str:
    rgb = subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-i", str(src), "-vf", "crop=8:8:10:10,scale=1:1",
         "-f", "rawvideo", "-pix_fmt", "rgb24", "-"],
        check=True, capture_output=True,
    ).stdout
    return "0x" + rgb[:3].hex()


def main():
    found: dict[str, list[str]] = {}
    for gid in LINES["girls"]:
        for emo in EMOTIONS:
            src = next((p for p in (RAW / f"{gid}_{emo}.png", RAW / f"{gid}_{emo}.jpg", RAW / f"{gid}_{emo}.jpeg",
                                     RAW / f"{gid}_{emo}.webp") if p.exists()), None)
            if not src:
                continue
            ffmpeg(src, OUT / f"{gid}_{emo}.jpg", 512, ["-q:v", "3"])
            found.setdefault(gid, []).append(emo)

    icon = next((p for p in (RAW / "icon.png", RAW / "icon.jpg", RAW / "icon.webp") if p.exists()), None)
    if icon:
        ffmpeg(icon, ROOT / "assets/icon.png", 1024, [])
        ffmpeg(icon, ROOT / "assets/favicon.png", 48, [])
        # Android masks adaptive icons to the middle ~2/3, so shrink the art into that safe zone
        # and fill the rest (and the background layer) with the icon's own corner colour.
        bg = corner_color(icon)
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(icon), "-vf",
                        f"{CROP},scale=700:700:flags=lanczos,pad=1024:1024:162:162:color={bg}",
                        str(ROOT / "assets/android-icon-foreground.png")], check=True)
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "lavfi", "-i", f"color=c={bg}:s=1024x1024",
                        "-frames:v", "1", str(ROOT / "assets/android-icon-background.png")], check=True)

    # Screen-time overlay animations: play forward then backward so the loop has no jump,
    # drop the audio (she speaks with her own voice clips) and keep them small.
    videos = []
    for gid in LINES["girls"]:
        src = RAW / "video" / f"{gid}.mp4"
        if not src.exists():
            continue
        dest = ROOT / "assets/guard" / f"{gid}.mp4"
        dest.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            ["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-filter_complex",
             f"[0:v]{CROP},scale=480:480:flags=lanczos,fps=24,split[a][b];[b]reverse[r];[a][r]concat=n=2:v=1:a=0,format=yuv420p",
             "-an", "-c:v", "libx264", "-profile:v", "main", "-crf", "30", "-preset", "slow",
             "-movflags", "+faststart", str(dest)],
            check=True,
        )
        videos.append(gid)
    VIDEO_INDEX.write_text("\n".join([
        "// Generated by scripts/process_art.py. Do not edit by hand.",
        "// Short looping animations (made with Grok from each girl's art) for the screen-time overlay.",
        "// A girl without a video shows her portrait instead.",
        "",
        "import { GirlId } from './girls';",
        "",
        "export const GUARD_VIDEOS: Partial<Record<GirlId, number>> = {",
        *(f"  {gid}: require('../../assets/guard/{gid}.mp4')," for gid in videos),
        "};",
        "",
    ]))

    lines = ["// Generated by scripts/process_art.py. Do not edit by hand.", "",
             "import { Emotion, GirlId } from './girls';", "",
             "export const ART: Partial<Record<GirlId, Partial<Record<Emotion, number>>>> = {"]
    for gid, emos in found.items():
        entries = ", ".join(f"{e}: require('../../assets/girls/{gid}_{e}.jpg')" for e in emos)
        lines.append(f"  {gid}: {{ {entries} }},")
    lines += ["};", ""]
    INDEX.write_text("\n".join(lines))
    total = sum(len(v) for v in found.values())
    print(f"{total} portraits processed, icon: {'yes' if icon else 'no'}. Wrote {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
