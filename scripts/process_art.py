#!/usr/bin/env python3
"""Turn the Grok images in art/raw/ into app assets.

  art/raw/<girl>_<emotion>.png  →  assets/girls/<girl>_<emotion>.jpg  (512×512, centre crop)
  art/raw/icon.png              →  assets/icon.png, assets/android-icon-foreground.png (1024×1024)

Writes src/data/art.ts with a require() for every portrait that exists, so the app shows real
art where it has it and falls back to the drawn faces elsewhere. Needs ffmpeg.
Run it again any time you add or replace images.
"""

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "art/raw"
OUT = ROOT / "assets/girls"
INDEX = ROOT / "src/data/art.ts"
LINES = json.loads((ROOT / "src/data/lines.json").read_text())
EMOTIONS = ["love", "angry", "miss", "shy", "night", "call"]
CROP = "crop='min(iw,ih)':'min(iw,ih)'"


def ffmpeg(src: Path, dest: Path, size: int, extra: list[str]):
    dest.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-vf", f"{CROP},scale={size}:{size}:flags=lanczos",
         *extra, str(dest)],
        check=True,
    )


def main():
    found: dict[str, list[str]] = {}
    for gid in LINES["girls"]:
        for emo in EMOTIONS:
            src = next((p for p in (RAW / f"{gid}_{emo}.png", RAW / f"{gid}_{emo}.jpg", RAW / f"{gid}_{emo}.jpeg",
                                     RAW / f"{gid}_{emo}.webp") if p.exists()), None)
            if not src:
                continue
            ffmpeg(src, OUT / f"{gid}_{emo}.jpg", 512, ["-q:v", "3"])
            found.setdefault(gid, []).append(emo)

    icon = next((p for p in (RAW / "icon.png", RAW / "icon.jpg", RAW / "icon.webp") if p.exists()), None)
    if icon:
        ffmpeg(icon, ROOT / "assets/icon.png", 1024, [])
        ffmpeg(icon, ROOT / "assets/android-icon-foreground.png", 1024, [])

    lines = ["// Generated by scripts/process_art.py. Do not edit by hand.", "",
             "import { Emotion, GirlId } from './girls';", "",
             "export const ART: Partial<Record<GirlId, Partial<Record<Emotion, number>>>> = {"]
    for gid, emos in found.items():
        entries = ", ".join(f"{e}: require('../../assets/girls/{gid}_{e}.jpg')" for e in emos)
        lines.append(f"  {gid}: {{ {entries} }},")
    lines += ["};", ""]
    INDEX.write_text("\n".join(lines))
    total = sum(len(v) for v in found.values())
    print(f"{total} portraits processed, icon: {'yes' if icon else 'no'}. Wrote {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
