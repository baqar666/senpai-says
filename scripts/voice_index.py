"""Writes src/data/voice-assets.ts, the require() index of every voice clip, for both languages."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINES = json.loads((ROOT / "src/data/lines.json").read_text())
NAMES = json.loads((ROOT / "src/data/names.json").read_text())["names"]
# Japanese also has a larger list; English falls back to Senpai for these until generated.
NAMES_JP = NAMES + json.loads((ROOT / "src/data/names_jp_extra.json").read_text())["names"]
NAMES_BY_LANG = {"jp": NAMES_JP, "en": NAMES}
VOICES = ROOT / "assets/voices"
INDEX = ROOT / "src/data/voice-assets.ts"
LANGS = ("jp", "en")
LEADING_PUNCT = "…。！？、!?., "


def write_index():
    def req(p: str) -> str:
        path = VOICES / p
        if not path.exists():
            raise SystemExit(f"Missing clip {path}. Run both generators before building.")
        return f"require('../../assets/voices/{p}')"

    out = ["// Generated by scripts/voice_index.py. Do not edit by hand.", "", "export const VOICE_CLIPS = {"]
    for lang in LANGS:
        out.append(f"  {lang}: {{")
        for gid in LINES["girls"]:
            out.append(f"    {gid}: {{")
            out.append("      lines: {")
            for lkey in LINES["lines"][gid]:
                # New lines may exist in one language before the other is generated; the app hides those.
                if not all((VOICES / f"{lang}/{gid}/lines/{lkey}_{h['key']}.mp3").exists() for h in LINES["honorifics"]):
                    print(f"  skipping {lang}/{gid}/{lkey} (not generated yet)")
                    continue
                hons = ", ".join(
                    f"{h['key']}: {req(f'{lang}/{gid}/lines/{lkey}_{h['key']}.mp3')}" for h in LINES["honorifics"]
                )
                out.append(f"        {lkey}: {{ {hons} }},")
            out.append("      },")
            out.append("      names: {")
            for entry in NAMES_BY_LANG[lang]:
                tones = ", ".join(f"{t}: {req(f'{lang}/{gid}/names/{entry[1]}_{t}.mp3')}" for t in ("soft", "loud"))
                out.append(f"        '{entry[1]}': {{ {tones} }},")
            out.append("      },")
            out.append("    },")
        out.append("  },")
    out.append("} as const;")
    out.append("")
    # Some voices' terms ask for a specific credit (girl "credit" in lines.json); otherwise the voice name.
    credits = [f"VOICEVOX:{c}" for c in sorted({g.get("credit", g["speaker"]) for g in LINES["girls"].values()})]
    credits.append("Orpheus TTS (English, Built with Llama)")
    out.append(f"export const VOICE_CREDITS = {json.dumps(credits, ensure_ascii=False)};")
    out.append("")
    INDEX.write_text("\n".join(out))
    print(f"Wrote {INDEX.relative_to(ROOT)}")


if __name__ == "__main__":
    write_index()
